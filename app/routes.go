// hello greets by name. Greeting is defined in schema.lidza.
func hello(ctx context.Context, req *router.Request[router.None]) (schema.Greeting, error) {
	name := req.Param("name")
	return schema.Greeting{Name: name, Message: "hello, " + name}, nil
}
