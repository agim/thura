import { expect, test } from '@playwright/test'
import { resolve } from 'node:path'

for (const width of [1440, 390]) test(`actual mail wizard separates ingress and outgoing controls at ${width}px`, async ({page}) => {
 await page.setViewportSize({width, height:900})
 await page.goto('/app')
 await page.getByLabel('Email',{exact:true}).fill('operator@outside.example')
 await page.getByLabel('Password',{exact:true}).fill('PUBLIC-compose fixture river maple 8429')
 await page.getByRole('button',{name:'Sign in',exact:true}).click()
 await expect(page.getByRole('button',{name:'New message',exact:true})).toBeVisible()
 await page.goto('/admin/setup?step=mail')
 const incoming=page.getByRole('combobox',{name:'Receive email through',exact:true})
 const outgoing=page.getByRole('combobox',{name:'Send email through',exact:true})
 const provider=page.getByRole('combobox',{name:'Outgoing provider',exact:true})
 await expect(incoming).toBeVisible()
 await expect(outgoing).toBeVisible()
 await expect(page.getByLabel('Mail server hostname',{exact:true})).toHaveValue('mail.team.example')
 await outgoing.click()
 await page.getByRole('option',{name:'postfix',exact:true}).click()
 await expect(provider).toBeHidden()
 await expect(page.getByLabel('SMTP hostname',{exact:true})).toBeHidden()
 await outgoing.click()
 await page.getByRole('option',{name:'provider',exact:true}).click()
 await provider.click()
 await page.getByRole('option',{name:'mailgun',exact:true}).click()
 await expect(page.getByLabel('Email API key',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Mailgun sending domain',{exact:true})).toBeVisible()
 await expect(page.getByLabel('SMTP hostname',{exact:true})).toBeHidden()
 await incoming.click()
 await page.getByRole('option',{name:'relay',exact:true}).click()
 await expect(page.getByLabel('Inbound relay signing secret',{exact:true})).toBeVisible()
 await expect(page.getByLabel('Mail server hostname',{exact:true})).toBeHidden()
 await incoming.click()
 await page.getByRole('option',{name:'postfix',exact:true}).click()
 await expect(page.getByLabel('Inbound relay signing secret',{exact:true})).toBeHidden()
 const secretValues=await page.locator('input[type="password"]').evaluateAll(inputs=>inputs.map(input=>(input as HTMLInputElement).value))
 expect(secretValues.every(value=>value==='')).toBe(true)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
 await page.screenshot({path:resolve(`.lidza/postfix-wizard-${width}.png`),fullPage:true})
})
