  const panel = page.getByRole('complementary', { name: 'AI assistant', exact: true })
  await page.locator('.mailrow').first().click()
  await expect(panel.locator('.assistant-source')).not.toContainText('visible messages')
  await panel.getByText('Review included text', { exact: true }).click()
  await expect(panel.getByLabel('Text included', { exact: true })).toHaveValue(/From:/)
  await panel.getByRole('button', { name: 'Summarize', exact: true }).click()
  await expect.poll(() => started).toBe(true)
  await page.getByRole('link', { name: 'Drive', exact: true }).click()
