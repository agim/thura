  expect(inputs[1]).not.toContain('First conversation')
  await panel.getByRole('button', { name: 'Insert in composer', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('Reviewed chat draft')
  await page.getByLabel('Chat room', { exact: true }).getByRole('button', { name: /First conversation/ }).click()
  await expect(page.getByRole('textbox', { name: 'Message', exact: true })).toHaveValue('')
