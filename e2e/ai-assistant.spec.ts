  const panel = page.getByRole('complementary', { name: 'AI assistant', exact: true })
  await panel.getByRole('button', { name: 'Summarize', exact: true }).click()
  await expect(panel.locator('.assistant-output')).toHaveText('Reviewed chat draft')
  await page.getByLabel('Chat room', { exact: true }).getByRole('button', { name: /Second conversation/ }).click()
