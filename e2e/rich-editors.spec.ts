import { expect, test } from '@playwright/test'
import { chooseOption } from './controls'

for (const width of [1440, 390]) test(`formatted compose persists and recipients stay in separate inline rows at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/app')
  await page.getByLabel('Email', { exact: true }).fill('owner-e2e@example.com')
  await page.getByLabel('Password', { exact: true }).fill('thura fixture maple lantern 4829')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'New message', exact: true }).click()
  const subject = `Formatted draft ${width} ${Date.now()}`
  await page.getByLabel('To', { exact: true }).fill('first@example.com')
  await page.getByLabel('To', { exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Cc / Bcc', exact: true }).click()
  for (const field of ['Cc', 'Bcc']) {
    await page.getByLabel(field, { exact: true }).fill(`${field.toLowerCase()}@example.com`)
    await page.getByLabel(field, { exact: true }).press('Enter')
    await expect(page.getByRole('button', { name: `Remove ${field.toLowerCase()}@example.com from ${field}`, exact: true })).toBeVisible()
  }
  const to = await page.getByLabel('To', { exact: true }).boundingBox()
  const cc = await page.getByLabel('Cc', { exact: true }).boundingBox()
  const bcc = await page.getByLabel('Bcc', { exact: true }).boundingBox()
  expect(cc!.y).toBeGreaterThan(to!.y)
  expect(bcc!.y).toBeGreaterThan(cc!.y)
  const label = await page.locator('.recipient-inline > label').first().boundingBox()
  expect(Math.abs(label!.y - to!.y)).toBeLessThan(18)
  await page.getByLabel('Subject', { exact: true }).fill(subject)
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  await page.getByRole('textbox', { name: 'Message', exact: true }).pressSequentially('Formatted plan')
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  await page.getByRole('textbox', { name: 'Message', exact: true }).press('End')
  await page.getByRole('textbox', { name: 'Message', exact: true }).press('Enter')
  await page.getByRole('textbox', { name: 'Message', exact: true }).pressSequentially('More detail')
  await expect(page.getByRole('textbox', { name: 'Message', exact: true }).locator('p')).toHaveCount(2)
  await page.getByRole('textbox', { name: 'Message', exact: true }).press('ControlOrMeta+a')
  await page.getByRole('button', { name: 'Insert link', exact: true }).click()
  await page.getByLabel('Link URL', { exact: true }).fill('https://example.com/plan')
  await page.getByRole('button', { name: 'Apply link', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Compose message', exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Save draft', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Draft saved')
  await page.reload()
  if (width < 1000) {
    await page.getByRole('button', { name: 'Account menu', exact: true }).click()
    await chooseOption(page.getByRole('combobox', { name: 'Mail folder', exact: true }), 'drafts')
  } else await page.getByRole('button', { name: 'Drafts', exact: true }).click()
  await page.getByRole('button').filter({ has: page.getByText(subject, { exact: true }) }).click()
  await expect(page.getByRole('textbox', { name: 'Message', exact: true }).locator('strong')).toHaveText('Formatted plan')
  await expect(page.getByRole('textbox', { name: 'Message', exact: true }).locator('a')).toHaveCount(2)
  await expect(page.getByRole('textbox', { name: 'Message', exact: true }).locator('a').first()).toHaveAttribute('href', 'https://example.com/plan')
  await expect(page.getByRole('button', { name: 'Remove cc@example.com from Cc', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Remove bcc@example.com from Bcc', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})

test('Drive document formatting saves immutable versions and reopens with tables intact', async ({ page }) => {
  await page.goto('/app')
  await page.getByLabel('Email', { exact: true }).fill('owner-e2e@example.com')
  await page.getByLabel('Password', { exact: true }).fill('thura fixture maple lantern 4829')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('link', { name: 'Drive', exact: true }).click()
  await page.getByRole('button', { name: 'New', exact: true }).click()
  await page.getByRole('button', { name: 'New document', exact: true }).click()
  const name = `Project notes ${Date.now()}`
  await page.getByLabel('Document name', { exact: true }).fill(name)
  await page.getByRole('button', { name: 'Create document', exact: true }).click()
  await page.getByRole('button', { name: 'Edit document', exact: true }).click()
  expect((await page.getByRole('textbox', { name: 'Document', exact: true }).boundingBox())!.width).toBeGreaterThan(700)
  expect((await page.getByRole('textbox', { name: 'Document', exact: true }).boundingBox())!.y).toBeLessThan(350)
  await page.getByRole('textbox', { name: 'Document', exact: true }).fill('Team planning')
  await page.getByRole('textbox', { name: 'Document', exact: true }).press('ControlOrMeta+a')
  await page.getByRole('button', { name: 'Bold', exact: true }).click()
  await page.getByRole('textbox', { name: 'Document', exact: true }).press('ArrowRight')
  await page.getByRole('textbox', { name: 'Document', exact: true }).press('End')
  await page.getByRole('textbox', { name: 'Document', exact: true }).press('Enter')
  await page.getByRole('button', { name: 'Insert table', exact: true }).click()
  await page.getByRole('button', { name: 'Save document', exact: true }).click()
  await expect(page.getByText('Saved version 2', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Close editor', exact: true }).click()
  await page.getByRole('button', { name: 'Edit document', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Document', exact: true }).locator('strong')).toHaveText('Team planning')
  await expect(page.getByRole('textbox', { name: 'Document', exact: true }).locator('table')).toHaveCount(1)
  await page.getByRole('textbox', { name: 'Document', exact: true }).fill('Recovered notes')
  await page.reload()
  await page.getByRole('button', { name: `${name}.html`, exact: true }).click()
  await page.getByRole('button', { name: 'Edit document', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'Document', exact: true })).toHaveText('Recovered notes')
  await expect(page.getByText('Recovered unsaved changes', { exact: true })).toBeVisible()
  await page.route('**/drive/uploads', route => route.fulfill({ status: 503, contentType: 'application/json', body: JSON.stringify({ error: 'Synthetic document storage unavailable' }) }))
  await page.getByRole('button', { name: 'Save document', exact: true }).click()
  await expect(page.getByLabel('Document editor').getByRole('alert')).toContainText('Synthetic document storage unavailable')
  await expect(page.getByRole('textbox', { name: 'Document', exact: true })).toHaveText('Recovered notes')
  await page.unroute('**/drive/uploads')
  await page.getByRole('button', { name: 'Save document', exact: true }).click()
  await expect(page.getByText('Saved version 3', { exact: true })).toBeVisible()

  await page.getByRole('button', { name: 'Version history', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Download version 1', exact: true })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Download version 2', exact: true })).toBeVisible()
})

for (const width of [1440, 390]) test(`calendar descriptions keep rich formatting and readable invitation text at ${width}px`, async ({ page }) => {
  await page.setViewportSize({ width, height: 900 })
  await page.goto('/app/calendar')
  await page.getByLabel('Email', { exact: true }).fill('owner-e2e@example.com')
  await page.getByLabel('Password', { exact: true }).fill('thura fixture maple lantern 4829')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await page.getByRole('button', { name: 'New event', exact: true }).click()
  const title = `Formatted event ${width} ${Date.now()}`
  await page.getByLabel('Event title', { exact: true }).fill(title)
  await page.getByRole('button', { name: 'Description and recurrence', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Description and recurrence', exact: true })
  await dialog.getByRole('textbox', { name: 'Description', exact: true }).fill('Review the launch plan')
  await dialog.getByRole('textbox', { name: 'Description', exact: true }).press('ControlOrMeta+a')
  await dialog.getByRole('button', { name: 'Bold', exact: true }).click()
  await dialog.getByRole('button', { name: 'Done', exact: true }).click()
  const save = page.waitForResponse(r => r.request().method() === 'POST' && /\/calendars\/[^/]+\/events$/.test(r.url()))
  await page.getByRole('button', { name: 'Save event', exact: true }).click()
  const response = await save
  expect(response.ok()).toBe(true)
  const result = await response.json()
  expect(result.event.description).toBe('Review the launch plan')
  expect(result.event.descriptionHtml).toBe('<p><strong>Review the launch plan</strong></p>')
  await page.locator('.fc').getByText(title, { exact: true }).first().click()
  await page.getByRole('button', { name: 'Description and recurrence', exact: true }).click()
  await expect(dialog.getByRole('textbox', { name: 'Description', exact: true }).locator('strong')).toHaveText('Review the launch plan')
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
})
